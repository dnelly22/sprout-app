/** Dev-time guard: required fields present and non-empty on every lesson. */
export function validateLessonContent(list: LessonContent[]): void {
  const seen = new Set<string>();
  for (const l of list) {
    if (seen.has(l.id)) throw new Error(`Duplicate lesson id: ${l.id}`);
    seen.add(l.id);
    if (!l.title?.trim()) throw new Error(`Lesson "${l.id}" missing title`);
    if (!l.shelf) throw new Error(`Lesson "${l.id}" missing shelf`);
    if (!l.whatsReallyGoingOn?.trim()) throw new Error(`Lesson "${l.id}" missing whatsReallyGoingOn`);
    if (!Array.isArray(l.areaTags)) throw new Error(`Lesson "${l.id}" areaTags must be an array`);
  }
}

if (import.meta.env.DEV) validateLessonContent(LESSON_CONTENT);
